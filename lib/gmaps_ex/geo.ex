defmodule GmapsEx.Geo do
  @moduledoc """
  Distance and grid helpers for geographic gap analysis.

  Deliberately not PostGIS: the working set is a few thousand rows, haversine is
  six lines, and an extension is a deployment dependency for no gain. The SQL
  form is generated by `sql_km_expr/4` from the same constant as the Elixir form
  so the two cannot silently drift — see the cross-check in the Malqa test.
  """

  @earth_km 6371.0088

  @doc "Great-circle distance in km between two lat/lon points."
  @spec haversine_km(float(), float(), float(), float()) :: float()
  def haversine_km(lat1, lon1, lat2, lon2) do
    dlat = deg(lat2 - lat1)
    dlon = deg(lon2 - lon1)

    a =
      :math.pow(:math.sin(dlat / 2), 2) +
        :math.cos(deg(lat1)) * :math.cos(deg(lat2)) * :math.pow(:math.sin(dlon / 2), 2)

    2 * @earth_km * :math.asin(:math.sqrt(min(1.0, a)))
  end

  @spec haversine_km({float(), float()}, {float(), float()}) :: float()
  def haversine_km({lat1, lon1}, {lat2, lon2}), do: haversine_km(lat1, lon1, lat2, lon2)

  @doc "The same formula as SQL, generated from one place so the two cannot drift."
  @spec sql_km_expr(String.t(), String.t(), String.t(), String.t()) :: String.t()
  def sql_km_expr(lat1, lon1, lat2, lon2) do
    """
    2 * #{@earth_km} * asin(sqrt(
      power(sin(radians(#{lat2} - #{lat1}) / 2), 2) +
      cos(radians(#{lat1})) * cos(radians(#{lat2})) *
      power(sin(radians(#{lon2} - #{lon1}) / 2), 2)
    ))
    """
    |> String.trim()
  end

  @doc "Bounding box of `radius_km` around a point, as `{min_lat, min_lon, max_lat, max_lon}`."
  @spec bbox_around(float(), float(), float()) :: {float(), float(), float(), float()}
  def bbox_around(lat, lon, radius_km) do
    dlat = radius_km / 110.574
    dlon = radius_km / (111.320 * :math.cos(deg(lat)))
    {lat - dlat, lon - dlon, lat + dlat, lon + dlon}
  end

  @doc """
  Grid of cell centres covering ±`hw_km` east/west and ±`hh_km` north/south of a
  point, stepping by `cell_km`.

  Extracted verbatim from the local `grid/6` that every existing mix task
  duplicates (e.g. `gmaps.riyadh_healthcare.ex`), inclusive upper bound and all,
  so cell counts match what those tasks produce.
  """
  @spec grid(float(), float(), float(), float(), float()) :: [{float(), float()}]
  def grid(lat, lon, hw_km, hh_km, cell_km) do
    step_lat = cell_km / 110.574
    step_lon = cell_km / (111.320 * :math.cos(deg(lat)))
    half_lat = hh_km / 110.574
    half_lon = hw_km / (111.320 * :math.cos(deg(lat)))

    for la <- frange(lat - half_lat, lat + half_lat, step_lat),
        lo <- frange(lon - half_lon, lon + half_lon, step_lon) do
      {la, lo}
    end
  end

  @doc "Count of cells `grid/5` would produce, without building them."
  @spec grid_count(float(), float(), float(), float(), float()) :: non_neg_integer()
  def grid_count(lat, lon, hw_km, hh_km, cell_km),
    do: length(grid(lat, lon, hw_km, hh_km, cell_km))

  @doc """
  Evenly spaced search origins across a bounding box.

  Used by the brand-name scan: searching a brand name from a handful of anchors at
  low zoom pulls that brand's branches from across the city in a few requests,
  instead of tiling the whole city with a fine grid.
  """
  @spec anchors({float(), float(), float(), float()}, pos_integer()) :: [{float(), float()}]
  def anchors({min_lat, min_lon, max_lat, max_lon}, n) do
    side = n |> :math.sqrt() |> Float.ceil() |> trunc()

    for i <- 1..side, j <- 1..side do
      {min_lat + (max_lat - min_lat) * (i - 0.5) / side,
       min_lon + (max_lon - min_lon) * (j - 0.5) / side}
    end
    |> Enum.take(n)
  end

  defp frange(start, stop, step) do
    Stream.unfold(start, fn v -> if v > stop, do: nil, else: {v, v + step} end)
    |> Enum.to_list()
  end

  defp deg(d), do: d * :math.pi() / 180.0
end
