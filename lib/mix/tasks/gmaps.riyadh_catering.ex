  ## Usage

      mix gmaps.riyadh_catering --csv riyadh-catering-leads.csv

  Add `--dry-run` to see the job count without enqueueing.
  Add `--jsonl riyadh-leads.jsonl` for JSONL output.
  Add `--sectors training,nonprofit,healthcare` to run a subset of categories.

  ## Scale

  ~380 queries (Arabic + English) × 15 zones × grid cells = a very large job
  count (`--dry-run` prints the exact number). Single IP this runs for many
  hours; use proxies (`GmapsEx.Http.ProxyPool`) and/or split the run by
  `--sectors` for something manageable. The `places` table accumulates across
  runs (upsert by place id), so batches are additive — nothing is lost between
  partial runs. Export at the end always reflects everything scraped so far.

  Each place is tagged with `input_id = "riyadh-catering:<zone>:<category>"`.

  Categories: corporate, government, healthcare, education, training, hotels,
  events, commercial, industrial, construction, financial, professional, tech,
  energy, automotive, logistics, nonprofit, sports, beauty, diplomatic, media,
  travel, military, labor_housing, social_care, aviation, research, religious,
  facility_mgmt, entertainment, bpo.

  ## Lead Classification

  Places are classified in the CSV based on review_rating and review_count:
    * ⭐ A+ (Hot Lead):   rating ≥ 4.0 AND reviews ≥ 50
    * ⭐ A  (Warm Lead):  rating ≥ 3.5 AND reviews ≥ 20
