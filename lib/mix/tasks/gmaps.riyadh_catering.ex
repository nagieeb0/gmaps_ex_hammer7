        cells = grid_count(hw, hh, cell)

        Mix.shell().info(
          "   #{tag}: #{cells} cells × #{n_queries} queries = #{cells * n_queries} jobs"
        )
      end

      Mix.shell().info(":: total: #{length(seeds)} seed jobs")
      System.halt(0)
    end

    Mix.Task.run("app.start")

    sc = opts[:search_concurrency] || 10
    pc = opts[:place_concurrency] || 20
    Oban.scale_queue(queue: :search, limit: sc)
    Oban.scale_queue(queue: :place, limit: pc)
    Mix.shell().info(":: concurrency search=#{sc} place=#{pc}")

    {:ok, n} = GmapsEx.Runner.start(seeds)
    Mix.shell().info(":: enqueued #{n} jobs")
    Mix.shell().info(":: DB accumulates — re-running with --sectors adds to existing rows")

    timeout_s = opts[:timeout] || 6 * 60 * 60
    attach_progress_logger()
    wait_for_completion(timeout_s)

    export_results(opts)
  end

  # ── Seed Generation ───────────────────────────────────────────────────

  # Restrict to a comma-separated list of category tags (e.g. --sectors training,nonprofit).
  # Lets a huge run be split into checkpointed batches — the DB accumulates across runs.
  defp filter_queries(nil), do: @queries

  defp filter_queries(csv) do
    wanted = csv |> String.split(",", trim: true) |> Enum.map(&String.trim/1) |> MapSet.new()
    filtered = Enum.filter(@queries, fn {tag, _q} -> MapSet.member?(wanted, tag) end)

    if filtered == [] do
      Mix.raise(
        "no queries match --sectors #{csv}. Available: " <>
          (@queries |> Enum.map(&elem(&1, 0)) |> Enum.uniq() |> Enum.join(", "))
      )
    end

    filtered
  end

  defp build_seeds(queries) do
    for {zone_tag, lat, lon, hw_km, hh_km, cell_km} <- @zones,
        {lat_c, lon_c} <- grid(lat, lon, hw_km, hh_km, cell_km),
        {cat_tag, query} <- queries do
      %{
        query: query,
        input_id: "riyadh-catering:#{zone_tag}:#{cat_tag}",
        lat: lat_c,
        lon: lon_c,
        zoom: 14,
        # Send each query under the locale that matches its script so Google's
        # language context lines up (English queries → hl=en). gl stays "sa".
        lang: query_lang(query),
        gl: "sa"
      }
    end
  end

  # ASCII-only query → English locale, otherwise Arabic.
  defp query_lang(query) do
    if String.match?(query, ~r/^[\x00-\x7F]+$/), do: "en", else: "ar"
  end

  defp grid(lat, lon, hw_km, hh_km, cell_km) do
    step_lat = cell_km / 110.574
    step_lon = cell_km / (111.320 * :math.cos(lat * :math.pi() / 180.0))
    half_lat = hh_km / 110.574
    half_lon = hw_km / (111.320 * :math.cos(lat * :math.pi() / 180.0))

    for la <- frange(lat - half_lat, lat + half_lat, step_lat),
        lo <- frange(lon - half_lon, lon + half_lon, step_lon) do
      {la, lo}
    end
  end

  defp grid_count(hw_km, hh_km, cell_km) do
    n_lat = trunc(2 * hh_km / cell_km) + 1
    n_lon = trunc(2 * hw_km / cell_km) + 1
    n_lat * n_lon
  end

  defp frange(start, stop, step) do
    Stream.unfold(start, fn v -> if v > stop, do: nil, else: {v, v + step} end)
    |> Enum.to_list()
  end

  # ── Export with Lead Classification ───────────────────────────────────

  @doc """
  Re-export the classified CSV from current DB state without scraping.
  Handy for resuming after a partial run finishes enrichment/emails.
  Returns the number of places written.
  """
  @spec write_csv(String.t()) :: non_neg_integer()
  def write_csv(path) do
    import Ecto.Query, only: [from: 2]

    # timeout: :infinity — loading tens of thousands of rows with big JSONB
    # columns can exceed the 15s default query timeout.
    places =
      GmapsEx.Repo.all(from(p in GmapsEx.Place, where: like(p.input_id, "riyadh-catering:%")),
        timeout: :infinity
      )

    write_classified_csv(places, path)
    length(places)
  end

  defp export_results(opts) do
    # ponytail: scope export to THIS scrape's rows. The DB is shared with other
    # scrapes (tanta, egypt-dentists, ...); Repo.all(Place) would dump all of them.
    import Ecto.Query, only: [from: 2]

    places =
      GmapsEx.Repo.all(from(p in GmapsEx.Place, where: like(p.input_id, "riyadh-catering:%")))

    Mix.shell().info(":: riyadh-catering places in DB: #{length(places)}")

    # Print classification summary
    classified = Enum.group_by(places, &classify_lead/1)

    for grade <- ["A+ (Hot Lead)", "A (Warm Lead)", "B (Potential)", "C (Cold Lead)"] do
      count = length(Map.get(classified, grade, []))
      Mix.shell().info("   #{grade}: #{count}")
    end

    if path = opts[:csv] do
      write_classified_csv(places, path)
      Mix.shell().info(":: wrote #{length(places)} places to #{Path.expand(path)}")
    end

    if path = opts[:jsonl] do
      GmapsEx.Output.Jsonl.write(places, path)
      Mix.shell().info(":: wrote #{length(places)} places to #{Path.expand(path)}")
    end

    # Always write a default CSV if no output specified
    if opts[:csv] == nil and opts[:jsonl] == nil do
      path = "riyadh-catering-leads.csv"
      write_classified_csv(places, path)
      Mix.shell().info(":: wrote #{length(places)} places to #{Path.expand(path)}")
    end
  end

  @doc false
  def classify_lead(place) do
    rating = place.review_rating || 0.0
    count = place.review_count || 0

    cond do
      rating >= 4.0 and count >= 50 -> "A+ (Hot Lead)"
      rating >= 3.5 and count >= 20 -> "A (Warm Lead)"
      rating >= 3.0 or count >= 10 -> "B (Potential)"
      true -> "C (Cold Lead)"
    end
  end

  # Writes CSV with all fields plus a lead_classification column
  defp write_classified_csv(places, path) do
    headers = [
      "lead_class",
      "title",
      "category",
      "categories",
      "address",
      "phone",
      "website",
      "emails",
      "review_rating",
      "review_count",
      "reviews_per_rating",
      "status",
      "price_range",
      "latitude",
      "longitude",
      "open_hours",
      "description",
      "owner_name",
      "owner_link",
      "place_id",
      "cid",
      "data_id",
      "link",
      "complete_address",
      "about",
      "reservations",
      "order_online",
      "menu",
      "input_id"
    ]

    rows =
      places
      |> Enum.sort_by(fn p ->
        grade_order =
          case classify_lead(p) do
            "A+ (Hot Lead)" -> 0
            "A (Warm Lead)" -> 1
            "B (Potential)" -> 2
            "C (Cold Lead)" -> 3
          end

        {grade_order, -(p.review_count || 0)}
      end)
      |> Enum.map(fn p ->
        [
          classify_lead(p),
          p.title || "",
          p.category || "",
          (p.categories || []) |> Enum.join(" | "),
          p.address || "",
          p.phone || "",
          p.website || "",
          (p.emails || []) |> Enum.join(" | "),
          to_string(p.review_rating || ""),
          to_string(p.review_count || ""),
          inspect_map(p.reviews_per_rating),
          p.status || "",
          p.price_range || "",
          to_string(p.latitude || ""),
          to_string(p.longitude || ""),
          inspect_map(p.open_hours),
          p.description || "",
          get_in_safe(p.owner, "name"),
          get_in_safe(p.owner, "link"),
          p.place_id || "",
          p.cid || "",
          p.data_id || "",
          p.link || "",
          inspect_map(p.complete_address),
          inspect_list(p.about),
          inspect_list(p.reservations),
          inspect_list(p.order_online),
          inspect_map(p.menu),
          p.input_id || ""
        ]
      end)

    csv_content =
      [headers | rows]
      |> Enum.map(fn row ->
        row
        |> Enum.map(&csv_escape/1)
        |> Enum.join(",")
      end)
      |> Enum.join("\n")

    File.write!(path, "\uFEFF" <> csv_content)
  end

  defp csv_escape(val) when is_binary(val) do
    if String.contains?(val, [",", "\"", "\n", "\r"]) do
      "\"" <> String.replace(val, "\"", "\"\"") <> "\""
    else
      val
    end
  end

  defp csv_escape(val), do: to_string(val)

  defp inspect_map(nil), do: ""
  defp inspect_map(m) when map_size(m) == 0, do: ""
  defp inspect_map(m), do: Jason.encode!(m)

  defp inspect_list(nil), do: ""
  defp inspect_list([]), do: ""
  defp inspect_list(l), do: Jason.encode!(l)

  defp get_in_safe(nil, _key), do: ""
  defp get_in_safe(map, key) when is_map(map), do: Map.get(map, key, "") || ""
  defp get_in_safe(_, _), do: ""

  # ── Progress Logging ──────────────────────────────────────────────────

  defp attach_progress_logger do
    :telemetry.attach_many(
      "gmaps-riyadh-catering-progress",
      [
        [:gmaps_ex, :search, :ok],
        [:gmaps_ex, :place, :ok],
        [:gmaps_ex, :place, :error],
        [:gmaps_ex, :run, :complete]
      ],
      fn event, m, meta, _ ->
        case event do
          [:gmaps_ex, :search, :ok] ->
            # Log 1 in 20 to avoid flooding
            if Enum.random(1..20) == 1 do
              Mix.shell().info(":: search '#{meta[:query]}' → #{m[:count]} places")
            end

          [:gmaps_ex, :place, :ok] ->
            # Log high-value leads immediately
            rating = m[:review_rating] || 0
            count = m[:review_count] || 0

            if rating >= 4.0 and count >= 50 do
              Mix.shell().info(
                "   ★ HOT LEAD: #{meta[:title]} (#{rating}★, #{count} reviews, #{meta[:phone] || "no phone"})"
              )
            end

          [:gmaps_ex, :place, :error] ->
            :ok

          [:gmaps_ex, :run, :complete] ->
            Mix.shell().info(":: run complete (#{m[:places]} places across #{m[:seeds]} seeds)")
        end
      end,
      nil
    )
  end

  defp wait_for_completion(timeout_s) do
    parent = self()

    :ok =
      :telemetry.attach(
        "gmaps-riyadh-catering-wait",
        [:gmaps_ex, :run, :complete],
        fn _, _, _, _ -> send(parent, :riyadh_done) end,
        nil
      )

    receive do
      :riyadh_done -> :ok
    after
      timeout_s * 1000 ->
        Mix.shell().info(":: timeout after #{div(timeout_s, 3600)}h — partial results in DB")
        :ok
    end
  end
